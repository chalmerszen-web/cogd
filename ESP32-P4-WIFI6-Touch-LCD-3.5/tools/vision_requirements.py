"""Register legacy vision models with esp-dl's operator/kernel pruning.

The pinned face/pedestrian packages do not ship compile_req manifests. Their
FlatBuffer operator strings are length-prefixed, so collect exact known names;
retain the int8 convolution kernel family used by these quantized models.
Speech contributes its own int16 requirements independently.
"""
from pathlib import Path
import hashlib
import importlib.util
import json
import re
import struct

project = Path(__file__).resolve().parents[1]
managed = project / "managed_components"
dl = managed / "espressif__esp-dl"
spec = importlib.util.spec_from_file_location("dl_compile", dl / "cmake/compile_finalize.py")
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
operators = module.load_yaml(dl / "spec/ops.yml")["ops"]
kernels = module.kernel_symbol_list(module.load_yaml(dl / "spec/kernels.yml"))
models = [
    managed / "espressif__human_face_detect/models/p4/human_face_detect_msr_s8_v1.espdl",
    managed / "espressif__human_face_detect/models/p4/human_face_detect_mnp_s8_v1.espdl",
    managed / "espressif__pedestrian_detect/models/p4/pedestrian_detect_pico_s8_v1.espdl",
]
ops = set()
hashes = {}
for model in models:
    data = model.read_bytes()
    hashes[model.name] = hashlib.sha256(data).hexdigest()
    for name, definition in operators.items():
        for alias in [name, *definition.get("aliases", [])]:
            encoded = alias.encode("ascii")
            if struct.pack("<I", len(encoded)) + encoded + b"\0" in data:
                ops.add(name)
selected = sorted(k for k in kernels if re.search(r"(?:^|_)s8(?:_|$)", k.lower()))
assert {"Conv", "Concat", "GlobalAveragePool"} <= ops and selected
out = project / "components/p4_board/vision.compile_req.yml"
lines = ["# Generated by tools/vision_requirements.py; pinned int8 vision models."]
lines += [f"# {name}: {value}" for name, value in hashes.items()]
lines += ["ops:", *[f"  - {x}" for x in sorted(ops)], "kernels:", *[f"  - {x}" for x in selected]]
out.write_text("\n".join(lines) + "\n", encoding="utf8")
print(json.dumps({"ops": sorted(ops), "kernels": len(selected)}))
