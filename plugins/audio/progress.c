size_t agent_progress_render(agent_progress_t *s, int16_t *pcm, size_t capacity)
{
    if (!s || !pcm || !s->data || s->block_bytes<4) return 0;
    size_t n=0;
    while (n<capacity && s->position<s->samples) {
        if (s->offset>=s->bytes) break;
        if (s->offset%s->block_bytes==0 && !s->high) {
            if (s->bytes-s->offset<4) break;
            const uint8_t *header=s->data+s->offset;
            if (header[2]>88 || header[3]) break;
            unsigned raw=(unsigned)header[0] | (unsigned)header[1]<<8;
            s->predictor=raw>=32768 ? (int)raw-65536 : (int)raw;
            s->index=header[2];s->offset+=4;
        } else {
            if (s->index<0 || s->index>88) break;
            unsigned code=(s->data[s->offset]>>(s->high ? 4 : 0))&15u;
            if (s->high) ++s->offset;
            s->high=!s->high;
            (void)agent_ima_decode(&s->predictor,&s->index,code);
        }
        pcm[n++]=(int16_t)s->predictor;++s->position;
    }
    return n;
}
