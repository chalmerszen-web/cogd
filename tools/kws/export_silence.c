static void i8(const char *name,const int8_t *p,size_t n)
{
    printf(".%s={",name);
    for(size_t i=0;i<n;++i)printf("%s%d%s",i?",":"",p[i],i%32==31?"\n":"");
    puts("},");
}
static void i16(const char *name,const int16_t *p,size_t n)
{
    printf(".%s={",name);
    for(size_t i=0;i<n;++i)printf("%s%d%s",i?",":"",p[i],i%32==31?"\n":"");
    puts("},");
}
static void neural(const char *name,const kws_neural_t *s)
{
    printf(".%s={\n",name);i8("history",s->history,sizeof(s->history));
    printf(".position={");for(unsigned i=0;i<6;++i)printf("%s%u",i?",":"",s->position[i]);puts("},");
    i8("current",s->current,sizeof(s->current));i8("next",s->next,sizeof(s->next));puts("},");
}
