    const int16_t zero[256]={0};kws_event_t event;
    for(unsigned frame=1;frame<=128;++frame) {
        assert(!kws_fusion_step_pcm(s,zero,(uint64_t)frame*256,&event,NULL));
        assert(!event.detected);
    }
    assert(s->last_sample==32768 && s->detector.blocks==64 && !s->detector.votes && !s->detector.cooldown_until);
