    i16("previous",s->first.previous,256);neural("first",&s->first.neural);neural("second",&s->second);
    printf(".detector={.last_sample=%llu,.cooldown_until=%llu,.blocks=%u,.votes=%u,.threshold_q8=%d},\n",
        (unsigned long long)s->detector.last_sample,(unsigned long long)s->detector.cooldown_until,
        s->detector.blocks,s->detector.votes,s->detector.threshold_q8);
    printf(".last_sample=%llu,\n",(unsigned long long)s->last_sample);
